import type { Trust } from "../model/model";
import type { PolicyDocument } from "../types";
import { EKS_COMMENTS, EKS_GROUP_COMMENT, EKS_VIEW_POLICY, eksClusters } from "./eks";
import { stringifyPolicy, type ExportFile } from "./json";
import { hclString, tfLabel, type ExportInput } from "./types";

const JSON_MARK = "ROLECRAFT_JSON";
const TAG = "Created with RoleCraft";
const HEADER = "# Generated by RoleCraft — https://rolecraft.omhinge.cloud";

type Attr = [key: string, value: string];
type PrincipalTrust = Extract<Trust, { kind: "principal" }>;

/** Policy JSON as heredoc body (column 0, so `<<-` strips nothing), with template sequences escaped. */
function heredocBody(doc: PolicyDocument): string {
  return stringifyPolicy(doc)
    .replace(/\$\{/g, () => "$${")
    .replace(/%\{/g, () => "%%{");
}

/** `=`-aligned attribute lines (as `terraform fmt` does). */
function attrLines(attrs: Attr[]): string[] {
  const width = Math.max(...attrs.map(([k]) => k.length));
  return attrs.map(([k, v]) => `  ${k.padEnd(width)} = ${v}`);
}

/** A resource block with aligned attributes and an optional heredoc JSON attribute. */
function resource(type: string, label: string, attrs: Attr[], json?: [key: string, doc: PolicyDocument]): string {
  const lines = [`resource "${type}" "${label}" {`, ...attrLines(attrs)];
  if (json) {
    // Blank lines isolate the multi-line attribute from fmt's alignment groups.
    lines.push("", `  ${json[0]} = <<-${JSON_MARK}`, heredocBody(json[1]) + JSON_MARK);
  }
  lines.push("}");
  return lines.join("\n");
}

/** `terraform {}` and the provider (plus a region variable when EKS needs a region we don't know). */
function preamble(region: string | undefined, needsEksRegion: boolean): string[] {
  const provider = (value: string): string => ['provider "aws" {', `  region = ${value}`, "}"].join("\n");
  const out = [
    [
      "terraform {",
      "  required_providers {",
      "    aws = {",
      '      source  = "hashicorp/aws"',
      // 5.33 EKS access entries; 5.35/5.37 IAM eventual-consistency retries; 5.81 optional OIDC thumbprint_list.
      '      version = ">= 5.81, < 7.0"',
      "    }",
      "  }",
      "}",
    ].join("\n"),
  ];
  if (region) {
    out.push(provider(hclString(region)));
  } else if (needsEksRegion) {
    out.push(
      ['variable "region" {', '  description = "AWS region of your EKS cluster(s)"', "  type        = string", "}"].join("\n"),
      provider("var.region"),
    );
  } else {
    out.push(
      ["# IAM is global; this region only selects the API endpoint Terraform calls.", provider('"us-east-1"')].join("\n"),
    );
  }
  return out;
}

/** Access entry + View policy association per cluster; `lead` lines are prefixed to the first block. */
function eksResources(label: string, clusters: string[], principalArn: string, lead: readonly string[]): string[] {
  return clusters.flatMap((c, i) => {
    const entry = `${label}_eks_${i + 1}`;
    const entryBlock = resource("aws_eks_access_entry", entry, [
      ["cluster_name", hclString(c)],
      ["principal_arn", principalArn],
    ]);
    const assoc = [
      `resource "aws_eks_access_policy_association" "${entry}_view" {`,
      ...attrLines([
        ["cluster_name", hclString(c)],
        ["principal_arn", principalArn],
        ["policy_arn", hclString(EKS_VIEW_POLICY)],
      ]),
      "",
      "  access_scope {",
      '    type = "cluster"',
      "  }",
      "",
      `  depends_on = [aws_eks_access_entry.${entry}]`,
      "}",
    ].join("\n");
    return [i === 0 ? [...lead, entryBlock].join("\n") : entryBlock, assoc];
  });
}

function principalBlocks(input: ExportInput, trust: PrincipalTrust, label: string, clusters: string[]): string[] {
  const { model, result } = input;
  const kind = trust.target;
  const who = hclString(trust.name);
  const inline = model.policyMode === "inline";
  const blocks: string[] = [];
  if (result.policy) {
    if (inline) {
      blocks.push(
        resource(
          `aws_iam_${kind}_policy`,
          `${label}_inline`,
          [
            ["name", hclString(`${model.name}-inline`)],
            [kind, who],
          ],
          ["policy", result.policy],
        ),
      );
    } else {
      blocks.push(
        resource(
          "aws_iam_policy",
          `${label}_policy`,
          [
            ["name", hclString(`${model.name}-policy`)],
            ["description", hclString(TAG)],
          ],
          ["policy", result.policy],
        ),
        resource(`aws_iam_${kind}_policy_attachment`, `${label}_policy`, [
          [kind, who],
          ["policy_arn", `aws_iam_policy.${label}_policy.arn`],
        ]),
      );
    }
  }
  model.managedPolicyArns.forEach((arn, i) => {
    blocks.push(
      resource(`aws_iam_${kind}_policy_attachment`, `${label}_managed_${i + 1}`, [
        [kind, who],
        ["policy_arn", hclString(arn)],
      ]),
    );
  });
  if (clusters.length > 0) {
    if (kind === "user") {
      // Looking the user up yields the real ARN (any path or partition) and fails at plan if the user is missing.
      const user = tfLabel(trust.name);
      blocks.push(
        [...EKS_COMMENTS, `data "aws_iam_user" "${user}" {`, `  user_name = ${who}`, "}"].join("\n"),
        ...eksResources(label, clusters, `data.aws_iam_user.${user}.arn`, []),
      );
    } else {
      blocks.push(EKS_GROUP_COMMENT);
    }
  }
  if (result.policy && !inline) {
    blocks.push(['output "policy_arn" {', `  value = aws_iam_policy.${label}_policy.arn`, "}"].join("\n"));
  }
  return blocks;
}

function roleBlocks(input: ExportInput, trustDoc: PolicyDocument, label: string, clusters: string[]): string[] {
  const { model, result } = input;
  const trust = model.trust;
  const roleRef = `aws_iam_role.${label}`;
  const blocks: string[] = [];
  if (trust.kind === "github") {
    blocks.push(
      [
        "# Uncomment if your account doesn't have the GitHub OIDC provider yet.",
        `# Then also add depends_on = [aws_iam_openid_connect_provider.github] to ${roleRef}.`,
        '# resource "aws_iam_openid_connect_provider" "github" {',
        '#   url            = "https://token.actions.githubusercontent.com"',
        '#   client_id_list = ["sts.amazonaws.com"]',
        "# }",
      ].join("\n"),
    );
  }
  blocks.push(
    resource(
      "aws_iam_role",
      label,
      [
        ["name", hclString(model.name)],
        ["description", hclString(TAG)],
      ],
      ["assume_role_policy", trustDoc],
    ),
  );
  if (result.policy) {
    if (model.policyMode === "inline") {
      blocks.push(
        resource(
          "aws_iam_role_policy",
          `${label}_inline`,
          [
            ["name", hclString(`${model.name}-inline`)],
            ["role", `${roleRef}.id`],
          ],
          ["policy", result.policy],
        ),
      );
    } else {
      blocks.push(
        resource(
          "aws_iam_policy",
          `${label}_policy`,
          [
            ["name", hclString(`${model.name}-policy`)],
            ["description", hclString(TAG)],
          ],
          ["policy", result.policy],
        ),
        resource("aws_iam_role_policy_attachment", `${label}_policy`, [
          ["role", `${roleRef}.name`],
          ["policy_arn", `aws_iam_policy.${label}_policy.arn`],
        ]),
      );
    }
  }
  model.managedPolicyArns.forEach((arn, i) => {
    blocks.push(
      resource("aws_iam_role_policy_attachment", `${label}_managed_${i + 1}`, [
        ["role", `${roleRef}.name`],
        ["policy_arn", hclString(arn)],
      ]),
    );
  });
  if (trust.kind === "service" && trust.service === "ec2") {
    blocks.push(
      [
        "# EC2 instances use roles through an instance profile.",
        resource("aws_iam_instance_profile", label, [
          ["name", hclString(model.name)],
          ["role", `${roleRef}.name`],
        ]),
      ].join("\n"),
    );
  }
  blocks.push(...eksResources(label, clusters, `${roleRef}.arn`, EKS_COMMENTS));
  blocks.push(['output "role_arn" {', `  value = ${roleRef}.arn`, "}"].join("\n"));
  return blocks;
}

/** Terraform configuration (AWS provider) that creates the role (or policy attached to a group/user). */
export function exportTerraform(input: ExportInput): ExportFile {
  const { model, result } = input;
  const trust = model.trust;
  const label = tfLabel(model.name);
  const clusters = eksClusters(model.grants);
  const finish = (blocks: string[]): ExportFile => ({
    filename: "main.tf",
    language: "hcl",
    content: blocks.join("\n\n").replace(/\n+$/, "") + "\n",
  });

  if (trust.kind === "principal") {
    return finish([
      [HEADER, `# Creates a permissions policy and attaches it to an existing IAM ${trust.target}.`].join("\n"),
      // Groups get only a comment (no access entries), so they don't need the EKS region.
      ...preamble(model.region, clusters.length > 0 && trust.target === "user"),
      ...principalBlocks(input, trust, label, clusters),
    ]);
  }
  if (!result.trust) {
    return finish([
      [
        HEADER,
        "# No trust policy could be generated, so no role was created. Fix the issues in RoleCraft and export again.",
      ].join("\n"),
    ]);
  }
  return finish([
    [HEADER, "# Creates an IAM role with its trust policy and permissions."].join("\n"),
    ...preamble(model.region, clusters.length > 0),
    ...roleBlocks(input, result.trust, label, clusters),
  ]);
}
