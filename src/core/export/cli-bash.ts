import type { Grant } from "../model/model";
import { stringifyPolicy, type ExportFile } from "./json";
import { shQuote, type ExportInput } from "./types";

const EOF_MARK = "ROLECRAFT_EOF";
const GITHUB_OIDC_CHECK =
  `if ! aws iam list-open-id-connect-providers --query "OpenIDConnectProviderList[?ends_with(Arn, '/token.actions.githubusercontent.com')].Arn" --output text | grep -q .; then ` +
  `aws iam create-open-id-connect-provider --url https://token.actions.githubusercontent.com --client-id-list sts.amazonaws.com; fi`;

function heredoc(file: string, body: string): string[] {
  return [`cat > ${file} <<'${EOF_MARK}'`, body.replace(/\n$/, ""), EOF_MARK];
}

function eksClusters(grants: Grant[]): string[] {
  const out: string[] = [];
  for (const g of grants) {
    if (g.module !== "eks" || g.service !== "eks" || g.access.type !== "preset") continue;
    if (g.access.preset !== "kubectl" || g.scope.type !== "module") continue;
    const data = g.scope.data as { cluster?: unknown } | null;
    const cluster = data && typeof data === "object" ? data.cluster : undefined;
    if (typeof cluster === "string" && cluster !== "" && !out.includes(cluster)) out.push(cluster);
  }
  return out;
}

/** Bash script that creates the role (or attaches the policy to a group/user) with the AWS CLI. */
export function exportCliBash(input: ExportInput): ExportFile {
  const { model, result } = input;
  const trust = model.trust;
  const lines: string[] = [];
  const add = (...l: string[]): void => {
    lines.push(...l);
  };
  const inline = model.policyMode === "inline";

  add("#!/usr/bin/env bash", "set -euo pipefail", "");
  add("# Generated by RoleCraft — https://rolecraft.omhinge.cloud");

  if (trust.kind === "principal") {
    const kind = trust.target;
    add(`# Creates a permissions policy and attaches it to an existing IAM ${kind}.`, "");
    add(`ROLE_NAME=${shQuote(model.name)}`, `PRINCIPAL_NAME=${shQuote(trust.name)}`, "");
    if (result.policy) add("# Permissions policy", ...heredoc("policy.json", stringifyPolicy(result.policy)), "");
    if (result.policy) {
      if (inline) {
        add(
          `aws iam put-${kind}-policy --${kind}-name "$PRINCIPAL_NAME" --policy-name "\${ROLE_NAME}-inline" --policy-document file://policy.json`,
        );
      } else {
        add(
          'POLICY_ARN=$(aws iam create-policy --policy-name "${ROLE_NAME}-policy" --policy-document file://policy.json --query Policy.Arn --output text)',
          `aws iam attach-${kind}-policy --${kind}-name "$PRINCIPAL_NAME" --policy-arn "$POLICY_ARN"`,
        );
      }
    }
    for (const arn of model.managedPolicyArns) {
      add(`aws iam attach-${kind}-policy --${kind}-name "$PRINCIPAL_NAME" --policy-arn ${shQuote(arn)}`);
    }
    if (eksClusters(model.grants).length > 0) {
      add(
        "",
        "# kubectl access: EKS access entries cannot target IAM groups or users, so this script does not create one.",
        "# Ask the cluster administrator to add an access entry or aws-auth mapping for the IAM user(s) instead.",
      );
    }
    add("", `echo "Attached the policy to ${kind} $PRINCIPAL_NAME."`);
    return finish("attach-policy.sh", lines);
  }

  add("# Creates an IAM role with its trust policy and permissions.", "");
  add(`ROLE_NAME=${shQuote(model.name)}`, "");

  if (!result.trust) {
    if (result.policy) add("# Permissions policy", ...heredoc("policy.json", stringifyPolicy(result.policy)), "");
    add(
      "# No trust policy could be generated, so no role was created. Fix the issues in RoleCraft and export again.",
      "",
      'echo "Nothing was created."',
    );
    return finish("create-role.sh", lines);
  }

  add("# Trust policy: who can assume the role", ...heredoc("trust.json", stringifyPolicy(result.trust)), "");
  if (result.policy) add("# Permissions policy", ...heredoc("policy.json", stringifyPolicy(result.policy)), "");

  if (trust.kind === "github") {
    add("# GitHub Actions needs an OIDC identity provider in this account (created once).", GITHUB_OIDC_CHECK, "");
  }
  add(
    "aws iam create-role --role-name \"$ROLE_NAME\" --assume-role-policy-document file://trust.json --description 'Created with RoleCraft'",
  );
  if (result.policy) {
    if (inline) {
      add(
        'aws iam put-role-policy --role-name "$ROLE_NAME" --policy-name "${ROLE_NAME}-inline" --policy-document file://policy.json',
      );
    } else {
      add(
        'POLICY_ARN=$(aws iam create-policy --policy-name "${ROLE_NAME}-policy" --policy-document file://policy.json --query Policy.Arn --output text)',
        'aws iam attach-role-policy --role-name "$ROLE_NAME" --policy-arn "$POLICY_ARN"',
      );
    }
  }
  for (const arn of model.managedPolicyArns) {
    add(`aws iam attach-role-policy --role-name "$ROLE_NAME" --policy-arn ${shQuote(arn)}`);
  }
  const ec2 = trust.kind === "service" && trust.service === "ec2";
  if (ec2) {
    add(
      "",
      "# EC2 instances use roles through an instance profile.",
      'aws iam create-instance-profile --instance-profile-name "$ROLE_NAME"',
      'aws iam add-role-to-instance-profile --instance-profile-name "$ROLE_NAME" --role-name "$ROLE_NAME"',
    );
  }

  const clusters = eksClusters(model.grants);
  if (clusters.length > 0) {
    const region = model.region ? ` --region ${shQuote(model.region)}` : "";
    add(
      "",
      "# Give the role kubectl access to your EKS cluster(s) through EKS access entries.",
      "# Change AmazonEKSViewPolicy to AmazonEKSEditPolicy or AmazonEKSClusterAdminPolicy if this role needs more.",
      'ROLE_ARN=$(aws iam get-role --role-name "$ROLE_NAME" --query Role.Arn --output text)',
    );
    for (const c of clusters) {
      add(
        `aws eks create-access-entry --cluster-name ${shQuote(c)} --principal-arn "$ROLE_ARN"${region}`,
        `aws eks associate-access-policy --cluster-name ${shQuote(c)} --principal-arn "$ROLE_ARN" --policy-arn arn:aws:eks::aws:cluster-access-policy/AmazonEKSViewPolicy --access-scope type=cluster${region}`,
      );
    }
  }

  add("", 'echo "Created role $ROLE_NAME."');
  if (ec2) add('echo "Created instance profile $ROLE_NAME."');
  if (result.policy) {
    add(
      inline
        ? 'echo "Added inline policy ${ROLE_NAME}-inline."'
        : 'echo "Created and attached policy ${ROLE_NAME}-policy."',
    );
  }
  return finish("create-role.sh", lines);
}

function finish(filename: string, lines: string[]): ExportFile {
  return { filename, language: "bash", content: lines.join("\n").replace(/\n+$/, "") + "\n" };
}
