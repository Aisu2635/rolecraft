import YAML, { type Scalar, type YAMLMap } from "yaml";
import type { RoleModel, Trust } from "../model/model";
import type { PolicyDocument } from "../types";
import { EKS_COMMENTS, EKS_GROUP_COMMENT, EKS_VIEW_POLICY, eksClusters, shortHash } from "./eks";
import { stringifyPolicy, type ExportFile } from "./json";
import { githubAccount, shQuote, TAG, type ExportInput } from "./types";

const HEADER = "# Generated by RoleCraft — https://rolecraft.omhinge.cloud";
const NO_TRUST =
  "# No trust policy could be generated, so no role was created. Fix the issues in RoleCraft and export again.";
const EKS_REGION = "# Deploy this stack in the region of your EKS cluster(s).";
const DO_NOT_DEPLOY = "# Do not deploy this file.";
const EKS_PROPAGATION =
  `# If this fails with "invalid principal" (IAM propagation delay), deploy again; if it was the stack's first deploy, delete the stack first (command at the top).`;
const USER_ARN_COMMENT = [
  "# This ARN assumes the user has no IAM path. CloudFormation can't look users up:",
  "# if the user has a path, replace PrincipalArn with the user's full ARN.",
];
const GITHUB_OIDC = [
  "# The trust policy uses the GitHub OIDC provider. If your account doesn't have it yet, add this resource and DependsOn: GitHubOidcProvider on Role:",
  "#   GitHubOidcProvider:",
  "#     Type: AWS::IAM::OIDCProvider",
  "#     Properties:",
  "#       Url: https://token.actions.githubusercontent.com",
  "#       ClientIdList:",
  "#         - sts.amazonaws.com",
];

type PrincipalTrust = Extract<Trust, { kind: "principal" }>;
type Resources = Record<string, { Type: string; DependsOn?: string[]; Properties: Record<string, unknown> }>;

interface Built {
  /** Header comment blocks after the deploy line (each line starts with `#`). */
  notes: (readonly string[])[];
  resources: Resources;
  outputs: Record<string, { Value: unknown }>;
  /** Comment lines placed directly above a resource. */
  resourceComments: Record<string, readonly string[]>;
}

/**
 * CloudFormation stack name derived from the role name: ^[a-zA-Z][-a-zA-Z0-9]*$, at most 128 characters.
 * Every other character (code point) becomes "-"; names not starting with a letter get a "rolecraft-" prefix.
 */
export function cfnStackName(name: string): string {
  const s = Array.from(name, (c) => (/^[-a-zA-Z0-9]$/.test(c) ? c : "-")).join("");
  const base = /^[a-zA-Z]/.test(s) ? s : `rolecraft-${s}`;
  // Any change (substitution, prefix, truncation) appends a hash of the original, so distinct names never share a stack.
  return base === name && base.length <= 128 ? base : `${base.slice(0, 119)}-${shortHash(name)}`;
}

const regionFlag = (model: RoleModel): string => (model.region ? ` --region ${shQuote(model.region)}` : "");

/** The command that deploys template.yaml (shown in the template header and the README). */
export function cfnDeployCommand(model: RoleModel): string {
  // --no-fail-on-empty-changeset: re-running an unchanged deploy exits 0 instead of 255.
  return `aws cloudformation deploy --template-file template.yaml --stack-name ${cfnStackName(model.name)} --capabilities CAPABILITY_NAMED_IAM --no-fail-on-empty-changeset${regionFlag(model)}`;
}

/** The command that deletes the stack (needed after a failed first deploy). */
export function cfnDeleteCommand(model: RoleModel): string {
  return `aws cloudformation delete-stack --stack-name ${cfnStackName(model.name)}${regionFlag(model)}`;
}

/**
 * Whether template.yaml has resources to deploy. It is comment-only when there is no trust policy, or when a
 * group/user only gets existing managed policies (CloudFormation can't attach those to an existing principal).
 */
export function cfnCanDeploy(input: ExportInput): boolean {
  const { model, result } = input;
  const trust = model.trust;
  if (trust.kind !== "principal") return result.trust !== null;
  return result.policy !== null || (trust.target === "user" && eksClusters(model.grants).length > 0);
}

/** Characters YAML 1.1 readers treat as line breaks or reject, which the serializer would write raw. */
function rawUnsafe(cp: number): boolean {
  return (cp >= 0x7f && cp <= 0x9f) || cp === 0x2028 || cp === 0x2029 || cp === 0xfeff || cp === 0xfffe || cp === 0xffff;
}

/** Strings that must be double-quoted: control/unsafe characters, lone surrogates, YAML 1.1 merge (`<<`) and value (`=`) keys. */
function forceQuote(s: string): boolean {
  if (s === "=" || s === "<<") return true;
  for (const c of s) {
    const cp = c.codePointAt(0) as number;
    if (cp < 0x20 || rawUnsafe(cp) || (cp >= 0xd800 && cp <= 0xdfff)) return true;
  }
  return false;
}

/** A single comment line that can't break out of the comment (no line breaks or unsafe characters). */
function commentSafe(line: string): string {
  return Array.from(line, (c) => {
    const cp = c.codePointAt(0) as number;
    return (cp < 0x20 && cp !== 0x09) || rawUnsafe(cp) || (cp >= 0xd800 && cp <= 0xdfff) ? "?" : c;
  }).join("");
}

/** Policy document as a plain object, parsed from the canonical JSON so content is identical everywhere. */
function policyObject(doc: PolicyDocument): unknown {
  return JSON.parse(stringifyPolicy(doc));
}

/** YAML 1.1-safe serialization (what CloudFormation reads), with comments above selected resources. */
function toYaml(template: Record<string, unknown>, resourceComments: Record<string, readonly string[]>): string {
  // Without the merge tag the serializer writes a "<<" string as a plain merge key; forceQuote quotes it instead.
  // CloudFormation rejects YAML aliases, so objects used twice (e.g. a shared PrincipalArn) are written out each time.
  const doc = new YAML.Document(template, {
    version: "1.1",
    aliasDuplicateObjects: false,
    customTags: (tags) => tags.filter((t) => typeof t === "string" || t.tag !== "tag:yaml.org,2002:merge"),
  });
  YAML.visit(doc, {
    Scalar(_, node) {
      if (typeof node.value === "string" && forceQuote(node.value)) node.type = "QUOTE_DOUBLE";
    },
  });
  // Built from a plain object, so Resources is a map with scalar keys.
  const resources = doc.get("Resources") as YAMLMap<Scalar<string>, unknown>;
  resources.items.forEach((pair, i) => {
    const lines = resourceComments[pair.key.value];
    if (!lines) return;
    // A blank line before the first resource would be indented (trailing whitespace) right after `Resources:`.
    pair.key.spaceBefore = i > 0;
    pair.key.commentBefore = lines.map((l) => l.replace(/^#/, "")).join("\n");
  });
  // Only double-quoted scalars can contain these now, and \uXXXX is a valid escape there in YAML 1.1 and 1.2.
  return doc
    .toString({ lineWidth: 0 })
    .replace(/[\u007f-\u009f\u2028\u2029\ufeff\ufffe\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

/**
 * Logical id per cluster (not a position), so adding, removing or reordering clusters never replaces another
 * cluster's access entry (EKS allows one per principal per cluster). A hash keeps lossy ids distinct.
 */
function eksLogicalId(cluster: string): string {
  const stripped = cluster.replace(/[^A-Za-z0-9]/g, "");
  const id = stripped.charAt(0).toUpperCase() + stripped.slice(1);
  return `EksAccessEntry${id === cluster ? id : `${id}${shortHash(cluster)}`}`;
}

/**
 * Access entry with the View policy (cluster scope) per cluster, after the template's IAM resources
 * (`dependsOn`) so new IAM objects exist first; `lead` comments go above the first entry.
 */
function addEksEntries(
  built: Built,
  clusters: string[],
  principalArn: unknown,
  dependsOn: string[],
  lead: readonly string[],
): void {
  clusters.forEach((c, i) => {
    const id = eksLogicalId(c);
    built.resources[id] = {
      Type: "AWS::EKS::AccessEntry",
      ...(dependsOn.length > 0 ? { DependsOn: dependsOn } : {}),
      Properties: {
        ClusterName: c,
        PrincipalArn: principalArn,
        AccessPolicies: [{ PolicyArn: EKS_VIEW_POLICY, AccessScope: { Type: "cluster" } }],
      },
    };
    if (i === 0) built.resourceComments[id] = [...lead, EKS_PROPAGATION];
  });
}

function attachCommands(kind: "group" | "user", name: string, arns: string[]): string[] {
  // --flag=value: IAM names may start with "-", which the AWS CLI would read as an option.
  return arns.map((arn) => `# aws iam attach-${kind}-policy --${kind}-name=${shQuote(name)} --policy-arn ${shQuote(arn)}`);
}

function principalTemplate(input: ExportInput, trust: PrincipalTrust, clusters: string[]): Built {
  const { model, result } = input;
  const kind = trust.target;
  const built: Built = { notes: [], resources: {}, outputs: {}, resourceComments: {} };
  if (result.policy) {
    if (model.policyMode === "inline") {
      built.resources.InlinePolicy = {
        Type: kind === "group" ? "AWS::IAM::GroupPolicy" : "AWS::IAM::UserPolicy",
        Properties: {
          [kind === "group" ? "GroupName" : "UserName"]: trust.name,
          PolicyName: `${model.name}-inline`,
          PolicyDocument: policyObject(result.policy),
        },
      };
    } else {
      built.resources.Policy = {
        Type: "AWS::IAM::ManagedPolicy",
        Properties: {
          ManagedPolicyName: `${model.name}-policy`,
          Description: TAG,
          PolicyDocument: policyObject(result.policy),
          [kind === "group" ? "Groups" : "Users"]: [trust.name],
        },
      };
      built.outputs.PolicyArn = { Value: { Ref: "Policy" } };
    }
  }
  if (model.managedPolicyArns.length > 0) {
    built.notes.push([
      `# CloudFormation can't attach existing managed policies to an existing ${kind}. Run this after deploying:`,
      ...attachCommands(kind, trust.name, model.managedPolicyArns),
    ]);
  }
  if (clusters.length > 0) {
    if (kind === "user") {
      const arn = {
        "Fn::Join": [
          "",
          ["arn:", { Ref: "AWS::Partition" }, ":iam::", { Ref: "AWS::AccountId" }, ":user/", trust.name],
        ],
      };
      addEksEntries(built, clusters, arn, Object.keys(built.resources), [...EKS_COMMENTS, ...USER_ARN_COMMENT]);
    } else {
      built.notes.push([EKS_GROUP_COMMENT]);
    }
  }
  return built;
}

function roleTemplate(input: ExportInput, trustDoc: PolicyDocument, clusters: string[]): Built {
  const { model, result } = input;
  const trust = model.trust;
  const built: Built = { notes: [], resources: {}, outputs: {}, resourceComments: {} };
  const account = githubAccount(model);
  // CloudFormation can't check this itself (Rules can't compare against AWS::AccountId), so it's a comment.
  if (account) {
    built.notes.push([
      `# Deploy this stack in account ${account}: the trust policy trusts GitHub through that account's OIDC provider.`,
    ]);
  }
  if (trust.kind === "github") built.notes.push(GITHUB_OIDC);
  const props: Record<string, unknown> = {
    RoleName: model.name,
    Description: TAG,
    AssumeRolePolicyDocument: policyObject(trustDoc),
  };
  const managed = model.policyMode !== "inline" && result.policy !== null;
  const arns: unknown[] = [...(managed ? [{ Ref: "Policy" }] : []), ...model.managedPolicyArns];
  if (arns.length > 0) props.ManagedPolicyArns = arns;
  if (result.policy && !managed) {
    props.Policies = [{ PolicyName: `${model.name}-inline`, PolicyDocument: policyObject(result.policy) }];
  }
  built.resources.Role = { Type: "AWS::IAM::Role", Properties: props };
  if (result.policy && managed) {
    built.resources.Policy = {
      Type: "AWS::IAM::ManagedPolicy",
      Properties: { ManagedPolicyName: `${model.name}-policy`, Description: TAG, PolicyDocument: policyObject(result.policy) },
    };
  }
  if (trust.kind === "service" && trust.service === "ec2") {
    built.resources.InstanceProfile = {
      Type: "AWS::IAM::InstanceProfile",
      Properties: { InstanceProfileName: model.name, Roles: [{ Ref: "Role" }] },
    };
    built.resourceComments.InstanceProfile = ["# EC2 instances use roles through an instance profile."];
  }
  // Role is already a dependency through Fn::GetAtt (listing it again is cfn-lint W3005).
  const others = Object.keys(built.resources).filter((k) => k !== "Role");
  addEksEntries(built, clusters, { "Fn::GetAtt": ["Role", "Arn"] }, others, EKS_COMMENTS);
  built.outputs.RoleArn = { Value: { "Fn::GetAtt": ["Role", "Arn"] } };
  return built;
}

function finish(lines: string[], body = ""): ExportFile {
  const head = lines.map(commentSafe).join("\n");
  return {
    filename: "template.yaml",
    language: "yaml",
    content: (body ? `${head}\n\n${body}` : head).replace(/\n+$/, "") + "\n",
  };
}

/** CloudFormation template (YAML, long-form intrinsics) that creates the role (or policy attached to a group/user). */
export function exportCloudFormation(input: ExportInput): ExportFile {
  const { model, result } = input;
  const trust = model.trust;
  const clusters = eksClusters(model.grants);

  let summary: string;
  let description: string;
  let built: Built;
  if (trust.kind === "principal") {
    built = principalTemplate(input, trust, clusters);
    if (!cfnCanDeploy(input)) {
      return finish([
        HEADER,
        DO_NOT_DEPLOY,
        `# Attaches existing managed policies to an existing IAM ${trust.target}.`,
        "# CloudFormation can't do this on its own; use the CLI script or Terraform instead.",
        ...attachCommands(trust.target, trust.name, model.managedPolicyArns),
        // Only a group can end up here with EKS clusters (a user gets access entries, so it has resources).
        ...(clusters.length > 0 ? ["", EKS_GROUP_COMMENT] : []),
      ]);
    }
    summary = `# Creates a permissions policy and attaches it to an existing IAM ${trust.target}.`;
    description = `RoleCraft: permissions policy for IAM ${trust.target} ${trust.name}`;
  } else if (result.trust) {
    built = roleTemplate(input, result.trust, clusters);
    summary = "# Creates an IAM role with its trust policy and permissions.";
    description = `RoleCraft: IAM role ${model.name}`;
  } else {
    return finish([HEADER, DO_NOT_DEPLOY, NO_TRUST]);
  }

  const hasEks = Object.values(built.resources).some((r) => r.Type === "AWS::EKS::AccessEntry");
  const head = [
    HEADER,
    summary,
    `# Deploy: ${cfnDeployCommand(model)}`,
    // A failed first deploy leaves the stack in ROLLBACK_COMPLETE, which can't be updated.
    `# If the first deploy fails, delete the stack (${cfnDeleteCommand(model)}) before deploying again.`,
    ...(hasEks && !model.region ? [EKS_REGION] : []),
  ];
  for (const block of built.notes) head.push("", ...block);
  const template: Record<string, unknown> = {
    AWSTemplateFormatVersion: "2010-09-09",
    Description: description,
    Resources: built.resources,
  };
  if (Object.keys(built.outputs).length > 0) template.Outputs = built.outputs;
  return finish(head, toYaml(template, built.resourceComments));
}
